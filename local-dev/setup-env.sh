#!/bin/bash
# Writes apps/*/.env for a real local test (Postgres + Valkey + LocalStack).
# Run AFTER: docker compose -f local-dev/docker-compose.yml up -d
# Usage: bash local-dev/setup-env.sh [--force]
#   --force  overwrite existing .env files (default: keep existing ones).
#
# What it generates (local-only secrets, never commit .env):
#   - random 32-byte base64 keys: NIK_ENCRYPTION_KEY, NIK_HMAC_KEY,
#     QR_HMAC_KEY, OTP_SECRET, SERVICE_KEY (core<->payment internal auth)
#   - one Ed25519 keypair (Node crypto): private JWK -> auth,
#     public JWK -> core / officer / admin (Q43, account-JWT verification)
#   - the shared local URLs (Postgres, Valkey, LocalStack, Dukcapil mock)
set -euo pipefail

FORCE=false
[ "${1:-}" = "--force" ] && FORCE=true
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

need() { command -v "$1" >/dev/null 2>&1 || { echo "missing: $1" >&2; exit 1; }; }
need openssl
need node

rand_b64() { openssl rand -base64 32 | tr -d '\n'; }
rand_hex() { openssl rand -hex 16 | tr -d '\n'; }

# Ed25519 keypair as JWK (private -> auth, public -> core/officer/admin).
# One keypair: generate once, then split it (a single `read` would put the
# whole first line into the first variable — read the two JWKs separately).
KEYPAIR_JSON="$(node -e "
const c = require('crypto');
const { publicKey, privateKey } = c.generateKeyPairSync('ed25519');
console.log(JSON.stringify({ priv: privateKey.export({ format: 'jwk' }), pub: publicKey.export({ format: 'jwk' }) }));
")"
PRIV_JWK="$(node -e "console.log(JSON.stringify(JSON.parse(process.argv[1]).priv))" "$KEYPAIR_JSON")"
PUB_JWK="$(node -e "console.log(JSON.stringify(JSON.parse(process.argv[1]).pub))" "$KEYPAIR_JSON")"
KID="local-dev-1"
PUB_JWKS_JSON="$(node -e "const k = JSON.parse(process.argv[1]); k.kid = process.argv[2]; console.log(JSON.stringify({ keys: [k] }));" "$PUB_JWK" "$KID")"
# officer wants { kid: JWK } (a map), not a JWKS array.
PUB_MAP_JSON="$(node -e "const k = JSON.parse(process.argv[1]); k.kid = process.argv[2]; console.log(JSON.stringify({ [process.argv[2]]: k }));" "$PUB_JWK" "$KID")"

NIK_ENC="$(rand_b64)"
NIK_HMAC="$(rand_b64)"
QR_HMAC="$(rand_b64)"
OTP_SECRET="$(rand_b64)"
SERVICE_KEY="$(rand_hex)"

DB_URL="postgres://rusuh:rusuh-dev@localhost:5432/rusuh"
VALKEY_URL="redis://localhost:6379"
AWS_REGION="ap-southeast-3"
AWS_ENDPOINT="http://localhost:4566"
SQS_BASE="http://localhost:4566/000000000000"
ADMISSION_Q="$SQS_BASE/rusuh-local-admission"
EMPTY_SLOT_Q="$SQS_BASE/rusuh-local-empty-slot"
OTP_Q="$SQS_BASE/rusuh-local-otp"
EMAIL_Q="$SQS_BASE/rusuh-local-email"

write_env() {
  app="$1"; shift
  file="apps/$app/.env"
  if [ -f "$file" ] && [ "$FORCE" = false ]; then
    echo "skip (exists, use --force to overwrite): $file"
    return
  fi
  {
    echo "# Generated by local-dev/setup-env.sh — LOCAL ONLY, never commit."
    echo "# Infra: docker compose -f local-dev/docker-compose.yml up -d"
    echo "NODE_ENV=development"
    echo "PORT=$1"; shift
    echo "DATABASE_URL=$DB_URL"
    echo "AWS_REGION=$AWS_REGION"
    echo "AWS_ACCESS_KEY_ID=test"
    echo "AWS_SECRET_ACCESS_KEY=test"
    echo "AWS_ENDPOINT_URL=$AWS_ENDPOINT"
    for line in "$@"; do echo "$line"; done
  } > "$file"
  echo "wrote $file"
}

write_env auth 8081 \
  "VALKEY_URL=$VALKEY_URL" \
  "SQS_QUEUE_URL=$OTP_Q" \
  "AUTH_JWT_PRIVATE_KEY_JWK=$PRIV_JWK" \
  "AUTH_JWT_KID=$KID" \
  "OTP_SECRET=$OTP_SECRET"

write_env core 8082 \
  "VALKEY_URL=$VALKEY_URL" \
  "DUKCAPIL_URL=http://localhost:18082" \
  "PAYMENT_URL=http://localhost:8083" \
  "SERVICE_KEY=$SERVICE_KEY" \
  "SQS_ADMISSION_QUEUE_URL=$ADMISSION_Q" \
  "SQS_EMPTY_SLOT_QUEUE_URL=$EMPTY_SLOT_Q" \
  "SQS_NOTIFICATION_QUEUE_URL=$EMAIL_Q" \
  "NIK_HMAC_KEY=$NIK_HMAC" \
  "NIK_ENCRYPTION_KEY=$NIK_ENC" \
  "QR_HMAC_KEY=$QR_HMAC" \
  "AUTH_JWKS=$PUB_JWKS_JSON" \
  "AUTH_AUDIENCE=rusuh-api" \
  "AUTH_ISSUER=rusuh-auth" \
  "PLATFORM_FEE_IDR=30000" \
  "ADMIN_FEE_IDR=15000" \
  "PPN_RATE=0.11" \
  "TAX2_RATE=0" \
  "TAX2_LABEL=Pajak Lainnya"

write_env payment 8083 \
  "MIDTRANS_SERVER_KEY=" \
  "MIDTRANS_CLIENT_KEY=" \
  "MIDTRANS_SNAP_BASE_URL=https://app.sandbox.midtrans.com/snap" \
  "MIDTRANS_API_BASE_URL=https://api.sandbox.midtrans.com" \
  "PAYMENT_STORE=postgres" \
  "CORE_INTERNAL_URL=http://localhost:8082" \
  "CORE_SERVICE_CREDENTIAL=$SERVICE_KEY"

write_env notification 8084 \
  "SQS_OTP_QUEUE_URL=$OTP_Q" \
  "SQS_EMAIL_QUEUE_URL=$EMAIL_Q" \
  "SES_FROM_EMAIL=noreply@rusuh-tiket.web.id" \
  "S3_TICKET_BUCKET=rusuh-local-tickets" \
  "ADMIN_EMAIL=admin@rusuh-tiket.web.id" \
  "WORKER_ENABLED=true"

write_env officer 8085 \
  "NIK_ENCRYPTION_KEY=$NIK_ENC" \
  "AUTH_PUBLIC_KEYS_JSON=$PUB_MAP_JSON" \
  "AUTH_AUDIENCE=rusuh-api" \
  "AUTH_ISSUER=rusuh-auth"

write_env admin 8086 \
  "AUTH_PUBLIC_KEY_JWK=$PUB_JWK" \
  "AUTH_AUDIENCE=rusuh-api" \
  "AUTH_ISSUER=rusuh-auth" \
  "QUEUE_ADMIN_URL=" \
  "QUEUE_ADMIN_TOKEN="

echo ""
echo "Done. Next:"
echo "  1. Fill MIDTRANS_SERVER_KEY + MIDTRANS_CLIENT_KEY in apps/payment/.env"
echo "     (sandbox, merchant 'edy' — server key is backend-only, never commit)."
echo "  2. Start the apps (one terminal each, or one at a time):"
echo "       cd apps/auth && npm start         # 8081"
echo "       cd apps/core && npm start         # 8082"
echo "       cd apps/payment && npm start      # 8083"
echo "       cd apps/notification && npm start # 8084"
echo "       cd apps/officer && npm start      # 8085"
echo "       cd apps/admin && npm start        # 8086"
echo "  3. PATCH /v1/admin/events/:id/queue will answer 503 until the queue"
echo "     service (rusuh-queue) runs — that proxy is out of scope here."
